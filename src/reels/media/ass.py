"""ASS subtitle files (rendered by libass via FFmpeg's `subtitles` filter)."""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

from reels.domain.subtitles import SubtitleEvent
from reels.settings_schema import SubtitleSettings

PLAY_RES = (1080, 1920)

# Static instance shipped in assets/fonts (see assets/fonts/README.md).
FONT_NAME = "Montserrat ExtraBold"


@dataclass(frozen=True)
class AssStyle:
    font_name: str
    font_size: int
    primary: str  # "#RRGGBB"
    accent: str
    outline_colour: str
    outline: float
    alignment: int  # numpad layout: 2 = bottom centre, 5 = middle, 8 = top centre
    margin_v: int
    margin_lr: int


# Vertical placement per position. lower_third keeps the text above Instagram's
# bottom controls (caption, buttons); values to be confirmed in the quality test.
_POSITIONS: dict[str, tuple[int, int]] = {
    "lower_third": (2, 500),
    "center": (5, 0),
    "upper_third": (8, 400),
}


def style_from_settings(s: SubtitleSettings) -> AssStyle:
    if s.style != "neutral":
        raise ValueError(f"unknown subtitle style {s.style!r}")
    alignment, margin_v = _POSITIONS[s.position]
    return AssStyle(
        font_name=FONT_NAME,
        font_size=72,
        primary="#FFFFFF",
        accent=s.accent_color,
        outline_colour="#000000",
        outline=6,
        alignment=alignment,
        margin_v=margin_v,
        margin_lr=60,
    )


def ass_colour(hex_rgb: str, alpha: int = 0) -> str:
    """'#RRGGBB' -> '&HAABBGGRR' (ASS stores blue first, alpha 00 = opaque)."""
    h = hex_rgb.lstrip("#")
    if len(h) != 6:
        raise ValueError(f"expected #RRGGBB, got {hex_rgb!r}")
    r, g, b = h[0:2], h[2:4], h[4:6]
    return f"&H{alpha:02X}{b}{g}{r}".upper()


def ass_override_colour(hex_rgb: str) -> str:
    """'#RRGGBB' -> '&HBBGGRR&' as used in override tags like {\\1c...}."""
    return "&H" + ass_colour(hex_rgb)[4:] + "&"


def ass_time(seconds: float) -> str:
    cs = max(round(seconds * 100), 0)
    h, rem = divmod(cs, 360000)
    m, rem = divmod(rem, 6000)
    s, cs = divmod(rem, 100)
    return f"{h}:{m:02d}:{s:02d}.{cs:02d}"


def escape_text(text: str) -> str:
    # Braces start override blocks and backslashes start escapes; neither belongs in speech.
    return text.replace("\\", "/").replace("{", "(").replace("}", ")").replace("\n", " ")


def _event_text(event: SubtitleEvent, style: AssStyle, karaoke: bool) -> str:
    accent = ass_override_colour(style.accent)
    parts: list[str] = []
    if karaoke:
        # Cumulative centiseconds avoid rounding drift across words.
        start_cs = round(event.start * 100)
        bounds = [round(w.start * 100) for w in event.words[1:]] + [round(event.end * 100)]
        prev = start_cs
        for w, bound in zip(event.words, bounds, strict=True):
            k = max(bound - prev, 0)
            prev = bound
            tag = f"\\k{k}"
            if w.highlight:
                tag += f"\\1c{accent}\\2c{accent}"
            parts.append("{" + tag + "}" + escape_text(w.text) + ("{\\r}" if w.highlight else ""))
        return " ".join(parts)
    for w in event.words:
        text = escape_text(w.text)
        parts.append("{\\1c" + accent + "}" + text + "{\\r}" if w.highlight else text)
    return " ".join(parts)


def render_ass(events: Sequence[SubtitleEvent], style: AssStyle, karaoke: bool = False) -> str:
    # Karaoke: words switch from Secondary (not yet spoken) to Primary (spoken).
    primary = ass_colour(style.accent if karaoke else style.primary)
    secondary = ass_colour(style.primary)
    style_line = ",".join(
        [
            "Style: Default",
            style.font_name,
            str(style.font_size),
            primary,
            secondary,
            ass_colour(style.outline_colour),
            ass_colour("#000000", alpha=0x80),
            "0,0,0,0",  # bold (instance is already ExtraBold), italic, underline, strikeout
            "100,100,0,0",  # scale x/y, spacing, angle
            "1",  # border style: outline + shadow
            f"{style.outline:g}",
            "0",  # shadow
            str(style.alignment),
            str(style.margin_lr),
            str(style.margin_lr),
            str(style.margin_v),
            "1",
        ]
    )
    lines = [
        "[Script Info]",
        "; generated by reels",
        "ScriptType: v4.00+",
        f"PlayResX: {PLAY_RES[0]}",
        f"PlayResY: {PLAY_RES[1]}",
        "WrapStyle: 0",
        "ScaledBorderAndShadow: yes",
        "YCbCr Matrix: TV.709",
        "",
        "[V4+ Styles]",
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, "
        "BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, "
        "BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding",
        style_line,
        "",
        "[Events]",
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
    ]
    for e in events:
        start, end = ass_time(e.start), ass_time(e.end)
        if end <= start:
            end = ass_time(e.start + 0.01)
        text = _event_text(e, style, karaoke)
        lines.append(f"Dialogue: 0,{start},{end},Default,,0,0,0,,{text}")
    return "\n".join(lines) + "\n"


def write_ass(
    path: Path, events: Sequence[SubtitleEvent], style: AssStyle, karaoke: bool = False
) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_ass(events, style, karaoke), encoding="utf-8")
    return path
